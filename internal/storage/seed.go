func Seed(storage *Storage) {
	ctx := context.Background()

	users := generateUsers(100)

	for _, user := range users {
		if err := storage.Users.Create(ctx, user); err != nil {
			log.Println("Error: ", err.Error())
			return
		}
	}

	posts := generatePosts(200, users)

	for _, post := range posts {
		if err := storage.Posts.Create(ctx, post); err != nil {
			log.Println("Error: ", err.Error())
			return
		}
	}

	comments := generateComments(500, users, posts)

	for _, comment := range comments {
		if err := storage.Comments.Create(ctx, comment); err != nil {
			log.Println("Error: ", err.Error())
			return
		}
	}

	log.Println("Seeding completed")
}

func generateUsers(n int) entity.Users {
	users := make(entity.Users, n)

	for i := 0; i < n; i++ {
		users[i] = &entity.User{
			Username: fmt.Sprintf("%s_%d_%d", usernames[i%len(usernames)], i, rand.Intn(1000000)),
			Email:    fmt.Sprintf("%s_%d_%d", usernames[i%len(usernames)], i, rand.Intn(1000000)) + "@example.com",
			RoleId:   1,
		}
	}

	return users
}

func generatePosts(n int, users entity.Users) entity.Posts {
	posts := make(entity.Posts, n)

	for i := 0; i < n; i++ {
		user := users[rand.Intn(len(users))]

		posts[i] = &entity.Post{
			UserId:  user.Id,
			Title:   titles[rand.Intn(len(titles))],
			Content: contents[rand.Intn(len(contents))],
			Tags: []string{
				tags[rand.Intn(len(tags))],
				tags[rand.Intn(len(tags))],
			},
		}
	}

	return posts
}

func generateComments(n int, users entity.Users, posts entity.Posts) entity.Comments {
	cms := make(entity.Comments, n)

	for i := 0; i < n; i++ {
		cms[i] = &entity.Comment{
			UserId:  users[rand.Intn(len(users))].Id,
			PostId:  posts[rand.Intn(len(posts))].Id,
			Content: comments[rand.Intn(len(comments))],
		}
	}

	return cms
}
